#!/usr/bin/env node
// Sync the Boxops design tokens into src/theme/boxops.generated.ts.
//
// The tokens live as StyleX `defineVars`/`defineConsts` calls in the Boxops
// monorepo (github.com/boxops-uk-scm/boxops, www/@boxops/ui/src). They are not
// published to npm, so this script fetches the two source files, evaluates
// them with a StyleX shim that returns the plain objects, and writes the
// values out as a TypeScript module the Astryx theme reads. Light/dark pairs
// (`{ default, '@media (prefers-color-scheme: dark)' }`) become `{ light, dark }`.
//
// Usage:
//   node scripts/sync-boxops-tokens.mjs                 # fetch via `gh api`
//   node scripts/sync-boxops-tokens.mjs --ref <git ref> # a branch, tag or sha
//   node scripts/sync-boxops-tokens.mjs --from <path>   # a local checkout's www/@boxops/ui/src
//
// Needs Node 22.18+ (it imports the .ts files directly).

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO = 'boxops-uk-scm/boxops';
const DIR = 'www/@boxops/ui/src';
const FILES = ['palette.stylex.ts', 'tokens.stylex.ts'];
const DARK = '@media (prefers-color-scheme: dark)';

const argv = process.argv.slice(2);
const opt = (name) => {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 ? argv[i + 1] : undefined;
};
const from = opt('from');
const ref = opt('ref');

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../src/theme/boxops.generated.ts');

function gh(args) {
  return execFileSync('gh', args, { encoding: 'utf8' });
}

function read(name) {
  if (from) return fs.readFileSync(path.join(from, name), 'utf8');
  const b64 = gh(['api', `repos/${REPO}/contents/${DIR}/${name}${ref ? `?ref=${ref}` : ''}`, '-q', '.content']);
  return Buffer.from(b64, 'base64').toString('utf8');
}

function source() {
  if (from) return `local checkout ${path.resolve(from)}`;
  const sha = gh(['api', `repos/${REPO}/commits/${ref ?? 'HEAD'}`, '-q', '.sha']).trim();
  return `${REPO}@${sha.slice(0, 12)}${ref ? ` (${ref})` : ''}`;
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'boxops-tokens-'));
fs.writeFileSync(
  path.join(tmp, 'stylex-shim.mjs'),
  'export const defineConsts = (o) => o;\nexport const defineVars = (o) => o;\nexport const createTheme = (_v, o) => o;\n',
);
for (const name of FILES) {
  const src = read(name)
    .replace(/from '@stylexjs\/stylex'/g, "from './stylex-shim.mjs'")
    .replace(/from '\.\/palette\.stylex'/g, "from './palette.stylex.ts'");
  fs.writeFileSync(path.join(tmp, name), src);
}
const palette = await import(pathToFileURL(path.join(tmp, 'palette.stylex.ts')).href);
const tokens = await import(pathToFileURL(path.join(tmp, 'tokens.stylex.ts')).href);

function token(v) {
  if (v && typeof v === 'object' && 'default' in v) {
    return DARK in v ? { light: v.default, dark: v[DARK] } : v.default;
  }
  return v;
}

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const lit = (v) =>
  typeof v === 'string' ? q(v) : `{ light: ${q(v.light)}, dark: ${q(v.dark)} }`;

const lines = [];
lines.push('// Generated by scripts/sync-boxops-tokens.mjs. Do not edit by hand.');
lines.push(`// Source: ${source()}  ${DIR}/{${FILES.join(',')}}`);
lines.push(`// Synced: ${new Date().toISOString()}`);
lines.push('');
lines.push('/** A value that differs between the light and dark colour schemes. */');
lines.push('export interface Modal {');
lines.push('  readonly light: string;');
lines.push('  readonly dark: string;');
lines.push('}');
lines.push('export type BoxopsToken = string | Modal;');
lines.push('');
lines.push('/** The raw OKLCH palette. Reach for the semantic groups below in components. */');
lines.push('export const palette = {');
for (const [k, v] of Object.entries(palette.palette)) lines.push(`  ${k}: ${q(v)},`);
lines.push('} as const;');

const groups = Object.entries(tokens)
  .filter(([, v]) => v && typeof v === 'object')
  .sort(([a], [b]) => a.localeCompare(b));
for (const [name, group] of groups) {
  lines.push('');
  lines.push(`export const ${name} = {`);
  for (const [k, v] of Object.entries(group)) lines.push(`  ${k}: ${lit(token(v))},`);
  lines.push('} as const;');
}
lines.push('');
fs.writeFileSync(out, lines.join('\n'));
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`wrote ${path.relative(process.cwd(), out)}: palette + ${groups.map(([n]) => n).join(', ')}`);
